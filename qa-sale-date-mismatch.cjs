const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');

const source=fs.readFileSync(path.join(__dirname,'daily-cycle.js'),'utf8');
const html=fs.readFileSync(path.join(__dirname,'dist/index.html'),'utf8');
const between=(text,start,end)=>{const a=text.indexOf(start),b=text.indexOf(end,a);assert(a>=0&&b>a,start);return text.slice(a,b);};
const helpers=between(source,'function saleRoot(month){','function showSaleTargets(month){');
assert.equal(helpers,between(html,'function saleRoot(month){','function showSaleTargets(month){'),'source/public parity');
const inputs=source.match(/^function dailyInputs\(now=Date\.now\(\)\)\{.*\}$/m)?.[0];
assert(inputs,'HOME completion source');
assert.equal(inputs,html.match(/^function dailyInputs\(now=Date\.now\(\)\)\{.*\}$/m)?.[0],'HOME source/public parity');

const oldInitial={saleDate:'2026-11-08',rows:[{skuId:'a',quantity:2},{skuId:'b',quantity:0}]};
const oldFinal={saleDate:'2026-11-08',rows:[{skuId:'a',quantity:2},{skuId:'b',quantity:3}]};
const demo={months:{'2026-11':{date:'2026-11-08'}},salesResults:{'2026-11':{initial:structuredClone(oldInitial),final:structuredClone(oldFinal)}},skus:[]};
const ctx={demo,Object,Map,structuredClone,allTasks:()=>[],jstDate:now=>new Date(now+9*3600000).toISOString().slice(0,10),dayAdd:(d,n)=>new Date(Date.parse(d+'T12:00:00Z')+n*86400000).toISOString().slice(0,10),endOfMonth:()=> '2026-11-30',short:d=>d.slice(5).replace('-','/'),reviewRecordForTask:()=>null};
vm.createContext(ctx);
vm.runInContext(helpers+inputs,ctx);
const month='2026-11';
assert.equal(ctx.salesResult(month).initial.rows[0].quantity,2);
assert.equal(ctx.saleDateMismatch(month),false);
demo.months[month].date='2026-11-09';
assert.equal(ctx.saleDateMismatch(month),true);
assert.equal(ctx.salesResult(month).initial,undefined,'old result cannot complete new date');
assert.deepEqual(Array.from(ctx.dailyInputs(Date.parse('2026-11-11T12:00:00Z')),r=>r.kind),['販売初動']);
assert.deepEqual(Array.from(ctx.dailyInputs(Date.parse('2026-11-30T12:00:00Z')),r=>r.kind),['販売初動','月次売上確定']);
const newInitial={saleDate:'2026-11-09',rows:[{skuId:'a',quantity:4},{skuId:'b',quantity:1}]};
ctx.saveSalesStage(month,'initial',structuredClone(newInitial));
assert.equal(ctx.salesResult(month).initial.rows[0].quantity,4);
assert.equal(ctx.salesResult(month).final,undefined);
assert.deepEqual(Array.from(ctx.dailyInputs(Date.parse('2026-11-11T12:00:00Z')),r=>r.kind),[]);
assert.deepEqual(Array.from(ctx.dailyInputs(Date.parse('2026-11-30T12:00:00Z')),r=>r.kind),['月次売上確定']);
const newFinal={saleDate:'2026-11-09',rows:[{skuId:'a',quantity:4},{skuId:'b',quantity:2}]};
ctx.saveSalesStage(month,'final',structuredClone(newFinal));
assert.equal(ctx.salesResult(month).final.rows[1].quantity,2,'new final stays with new initial');
assert.deepEqual(Array.from(ctx.dailyInputs(Date.parse('2026-11-30T12:00:00Z')),r=>r.kind),[]);
assert.deepEqual(demo.salesResults[month].initial,oldInitial,'old initial untouched');
assert.deepEqual(demo.salesResults[month].final,oldFinal,'old final untouched');
assert.deepEqual(JSON.parse(JSON.stringify(demo)).salesResults[month].bySaleDate['2026-11-09'].initial,newInitial,'reload preserves new date');
assert.deepEqual(JSON.parse(JSON.stringify(demo)).salesResults[month].bySaleDate['2026-11-09'].final,newFinal,'reload preserves new final');
demo.months[month].date='2026-11-08';
assert.equal(ctx.salesResult(month).initial.rows[0].quantity,2,'return uses original initial');
assert.equal(ctx.salesResult(month).final.rows[1].quantity,3,'return uses original final');
demo.months[month].date='2026-11-09';
assert.equal(ctx.salesResult(month).initial.rows[0].quantity,4,'new date still separate');
assert(source.includes('販売日が変更されています。')&&html.includes('販売日が変更されています。'),'HOME/month warning');
console.log('PASS sale date mismatch, separate records, HOME due, restore, JSON reload');
