const assert = require('node:assert/strict');
const {prepareStoryReplacement} = require('./dist/story-replacement-safety.js');
const clone = value => JSON.parse(JSON.stringify(value));
const old = {id:'story-old',date:'2026-10-11',slot:1,text:'元の文章',asset:'元の写真',reactionId:'reaction-old',shotId:'shot-old'};
const post = {id:'post-1',date:'2026-10-12',stories:[old],storyReplacementHistory:[]};
const reactions = [{id:'reaction-old',sourceStory:{postId:'post-1',slot:1,storyId:'story-old'}}];
const before = clone({post,reactions});
const result = prepareStoryReplacement(post,1,{id:'candidate',text:'新案',reactionId:'reaction-old',shotId:'shot-old'},reactions,{idFactory:()=> 'story-new'});
assert.equal(result.ok,true);
assert.equal(result.story.id,'story-new');
assert.equal(result.story.date,old.date);
assert.equal(result.story.slot,1);
assert.equal(result.story.reactionId,undefined);
assert.equal(result.story.shotId,undefined);
assert.deepEqual(result.history[0].story,old);
assert.equal(result.history[0].story.reactionId,'reaction-old');
assert.equal(result.history[0].story.shotId,'shot-old');
assert.deepEqual({post,reactions},before);
assert.deepEqual(JSON.parse(JSON.stringify(result.history)),result.history);
const ambiguous = prepareStoryReplacement(post,1,{text:'新案'},[{sourceStory:{postId:'post-1',slot:1}}],{idFactory:()=> 'story-new'});
assert.equal(ambiguous.ok,false);
assert.equal(prepareStoryReplacement(post,1,{text:'新案'},[{postId:'post-1',source:'Story'}],{idFactory:()=> 'story-new'}).ok,false);
assert.deepEqual({post,reactions},before);
const legacy = {id:'post-2',date:'2026-10-11',stories:[{slot:1,text:'旧案',asset:'写真'}]};
assert.equal(prepareStoryReplacement(legacy,1,{text:'新案'},[],{idFactory:()=> 'new-legacy'}).ok,true);
assert.equal(prepareStoryReplacement(legacy,1,{text:'新案'},[{sourceStory:{postId:'post-2',slot:1}}],{idFactory:()=> 'new-legacy'}).ok,false);
const repeated = {...post,storyReplacementHistory:result.history};
assert.equal(prepareStoryReplacement(repeated,1,{text:'新案'},reactions,{idFactory:()=> 'another'}).ok,false);
assert.equal(prepareStoryReplacement(post,1,{text:'新案'},reactions,{idFactory:()=> 'story-old'}).ok,false);
assert.equal(prepareStoryReplacement({...post,stories:[{...old,date:'2026-02-30'}]},1,{text:'新案'},[],{idFactory:()=> 'story-new'}).ok,false);
console.log('PASS Story replacement safety: identity, history, references, ambiguity, immutability, JSON roundtrip');
