const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const page=fs.readFileSync(path.join(__dirname,'dist/index.html'),'utf8');
const planner=fs.readFileSync(path.join(__dirname,'dist/period-planner.js'),'utf8');
const helper=page.slice(page.indexOf('function storyDate('),page.indexOf('function dayAdd(',page.indexOf('function storyDate(')));
const wrapper=planner.slice(planner.indexOf('const generateNewStoriesForBatch='),planner.indexOf('function duplicateReport(',planner.indexOf('const generateNewStoriesForBatch=')));
let next=0;
const sandbox={Set,demo:{posts:[]},V7StoryState:require('./dist/v7-story-state.js'),newId:()=>`story-${++next}`,generateStoriesForBatch:posts=>{
 for(const post of posts)post.stories=[1,2,3,4].map(slot=>({slot,text:`Story ${slot}`,asset:`photo ${slot}`}));
}};
vm.runInNewContext(helper+wrapper,sandbox);
const old={slot:1,text:'old'},saved={id:'post-old',date:'2026-10-11',stories:[old]};
assert.equal(sandbox.storyDate(old,saved),'2026-10-11','legacy date fallback');
assert.deepEqual(old,{slot:1,text:'old'},'reading does not mutate a legacy Story');
const created=[{id:'post-a',date:'2026-11-08',stories:[]},{id:'post-b',date:'2026-11-09',stories:[]}];
sandbox.generateStoriesForBatch(created);
const all=created.flatMap(post=>post.stories);
assert.equal(all.length,8);
assert.equal(new Set(all.map(story=>story.id)).size,8,'new IDs are unique');
for(const post of created)for(const story of post.stories)assert.equal(story.date,post.date);
assert.equal(JSON.stringify(JSON.parse(JSON.stringify(created))),JSON.stringify(created),'JSON roundtrip preserves IDs and dates');
const existing={id:'existing-id',date:'2026-10-11',slot:1,text:'keep'};
const unchanged=sandbox.newStoryIdentity(saved,existing);
assert.equal(unchanged.id,existing.id);assert.equal(unchanged.date,existing.date);
assert.deepEqual(existing,{id:'existing-id',date:'2026-10-11',slot:1,text:'keep'},'helper never mutates the source');
for(const date of ['2026-02-30','2026-13-01','2026-1-01','bad'])assert.throws(()=>sandbox.newStoryIdentity(saved,{date}),/日付/);
const savedBefore=JSON.stringify(saved);sandbox.demo.posts.push(saved);
assert.throws(()=>sandbox.generateStoriesForBatch([saved]),/保存済み/);
assert.equal(JSON.stringify(saved),savedBefore,'saved Stories are not regenerated');
sandbox.demo.posts=[{id:'moved-feed',date:'2026-11-12',stories:[{id:'kept-story',date:'2026-11-10',slot:1}]}];
const newFeed={id:'new-feed',date:'2026-11-10',stories:[]};
sandbox.generateStoriesForBatch([newFeed]);
assert.deepEqual(newFeed.stories.map(story=>story.slot),[2,3,4],'new Feed does not duplicate a Story-only day');
assert.match(planner,/generateStoriesForBatch\(created\)/,'only the new-post period path calls the wrapped generator');
console.log('PASS Story identity/date helper, new-post generation, legacy read, preservation, invalid-date rejection, JSON roundtrip');
