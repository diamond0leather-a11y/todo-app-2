const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const V7StoryState=require('./dist/v7-story-state.js');
const html=fs.readFileSync(path.join(__dirname,'dist/index.html'),'utf8');
const planner=fs.readFileSync(path.join(__dirname,'dist/period-planner.js'),'utf8');
const editorial=fs.readFileSync(path.join(__dirname,'dist/chatgpt-editorial.js'),'utf8');
const state={posts:[{id:'post-1',date:'2026-11-07',stories:[{id:'attached-1',date:'2026-11-05',slot:1,text:'Story1の編集済み本文',asset:'写真A'}]}],storyDays:[{id:'only-2',date:'2026-11-05',slot:2,text:'Story2の対話',asset:'写真B'},{id:'only-3',date:'2026-11-06',slot:3,text:'Story3の商品紹介'},{id:'duplicate',date:'2026-11-05',slot:1,text:'Story1の編集済み本文',asset:'写真A'}]};
const original=structuredClone(state);
const entries=V7StoryState.historyEntries(state,{from:'2026-11-05',to:'2026-11-06'});
assert.equal(entries.length,3,'standalone and attached Stories are included once');
assert.deepEqual(entries.map(entry=>[entry.date,entry.slot]),[['2026-11-06',3],['2026-11-05',1],['2026-11-05',2]],'Story date and slot are retained after Feed move');
assert.equal(entries.find(entry=>entry.slot===1).postId,null,'storyDays is the canonical history entry');
assert.equal(entries.find(entry=>entry.slot===2).postId,null);
const onDate=V7StoryState.entriesOnDate(state,'2026-11-05');
assert.equal(onDate.length,2,'legacy copy does not increase the visible count');
assert.equal(onDate.find(entry=>entry.slot===1).story.id,'duplicate','storyDays wins even with a different legacy ID');
assert.doesNotThrow(()=>V7StoryState.assertUnique(state,'2026-11-05',1,null,2),'editing the canonical Story is allowed');
const edited=structuredClone(state);
edited.storyDays[2].text='新しいStory本文';
assert.equal(V7StoryState.entriesOnDate(edited,'2026-11-05').length,2,'edited canonical Story still shadows the old text');
assert.equal(V7StoryState.historyEntries(edited,{from:'2026-11-05',to:'2026-11-05'}).length,2,'history does not restore the stale legacy copy after editing');
assert.equal(edited.posts[0].stories[0].text,'Story1の編集済み本文','legacy data remains untouched');
assert.deepEqual(state,original,'reading history never edits saved Stories');
const posted={posts:[{id:'posted',date:'2026-11-07',stories:[{id:'same-story',date:'2026-11-05',slot:1,text:'現在の予定'}],actualSnapshot:{stories:[{id:'same-story',slot:1,text:'実際に出した内容'}]}}],storyDays:[]};
const actual=V7StoryState.historyEntries(posted,{from:'2026-11-05',to:'2026-11-05'});
assert.equal(actual.length,1,'posted Story remains on its own date after the Feed move');
assert.equal(actual[0].story.text,'実際に出した内容','actual content is retained');
const context={demo:state,V7StoryState};
vm.createContext(context);
const snippet=(source,start,end)=>source.slice(source.indexOf(start),source.indexOf(end,source.indexOf(start)));
vm.runInContext(snippet(html,'function planningStoryHistory(','const salesPayload=analysisPayload;'),context);
const grouped=context.planningStoryHistory('2026-11-05','2026-11-06');
assert.equal(grouped.length,2,'analysis history includes standalone days without duplication');
assert.deepEqual(Array.from(grouped.find(row=>row.date==='2026-11-05').stories,story=>story.slot),[1,2]);
vm.runInContext(snippet(planner,'function recentStoryEntries(','function mainConflict('),context);
assert.equal(context.recentStoryEntries('2026-11-08').length,3,'next plan sees standalone Stories');
state.storyDays[0].text='Story2の修正後本文';state.storyDays.splice(1,1);
const changed=V7StoryState.historyEntries(state,{before:'2026-11-08'});
assert.equal(changed.length,2,'deleted Story is absent');
assert.equal(changed.find(entry=>entry.slot===2).story.text,'Story2の修正後本文','edited Story is current');
assert.match(editorial,/data\.storyHistory=V7StoryState\.historyEntries\(demo,\{before:from,limitDays:10\}\)/,'ten-day context uses the same history');
assert.match(editorial,/過去の文言や企画を機械的に繰り返さず/,'history is guidance, not compulsory reuse');
console.log('PASS v7 Story history: standalone, same-day dedupe, moved Feed, edit/delete, slots, next-plan/analysis paths');
