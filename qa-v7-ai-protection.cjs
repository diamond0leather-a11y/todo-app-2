const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const editorial=fs.readFileSync('dist/chatgpt-editorial.js','utf8');
const ui=fs.readFileSync('dist/v7-story-ui.js','utf8');
const ctx={demo:{reactions:[{sourceStory:{postId:'post-1',slot:1,storyId:'story-confirmed'}}]}};
vm.createContext(ctx);
vm.runInContext(editorial.slice(editorial.indexOf('function importProtection('),editorial.indexOf('function validateEditorialShots(')),ctx);
vm.runInContext(editorial.slice(editorial.indexOf('const protectedPost='),editorial.indexOf('function singlePrompt(')),ctx);
const post={id:'post-1',date:'2026-11-05',revision:1,stories:[{id:'story-confirmed'},{id:'story-open'}]};
assert.equal(ctx.importProtection(post).stories[0],true,'ten-day import preserves a Story with recorded responses');
assert.equal(ctx.importProtection(post).stories[1],false,'an unconfirmed Story may still be proposed');
assert.equal(vm.runInContext('protectedPost',ctx)(post),true,'single-day import cannot replace a responded Story');
assert.equal(vm.runInContext('protectedPost',ctx)({...post,stories:[{manual:true}]}),true,'manual Story is protected');
assert.match(ui,/aiFieldConflicts\(post,changes\)/,'analysis import checks manual field conflicts');
assert.match(ui,/approvedStories\.has\(`\$\{index\}\|\$\{slotIndex\}`\)/,'analysis import requires explicit per-slot approval');
assert.match(ui,/v7StoryHasReaction\(next,current\.story/,'analysis import blocks a Story with a recorded response');
assert.match(ui,/v7StoryHasReaction\(demo,post\?\.stories\[index\]/,'draft adoption blocks responded Stories');
console.log('PASS v7 AI protection: explicit per-slot consent and response locks');
