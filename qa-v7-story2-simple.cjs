const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const storyState=require('./dist/v7-story-state.js');
const result=require('./dist/v7-story2-result.js');
const stories=(kind='アンケート')=>[1,2,3,4].map(slot=>({id:'story-'+slot,slot,text:'Story '+slot,kind:slot===2?kind:'通常',options:slot===2?['A','B']:[],skuIds:[]}));
const post={id:'post-1',date:'2026-11-01',format:'Feed',stories:stories(),caption:'本文',manual:true};
const state={posts:[post],storyDays:[],reactions:[],records:{'review-1':{stage:'7d'}}};
const original=JSON.stringify({posts:state.posts,records:state.records});
assert.equal(result.pending(state,'2026-11-01',storyState).length,0,'予定日には案内しない');
assert.equal(result.pending(state,'2026-11-02',storyState).length,1,'翌日から質問・アンケートだけ案内');
const entry=result.pending(state,'2026-11-02',storyState)[0];
assert.equal(entry.slot,2);
assert.throws(()=>result.save(state,entry,'entered','',()=>{},()=> 'r-1'),/結果の文章/);
let saves=0;
result.save(state,entry,'entered','選択肢Aを選んだという声が多かった',()=>{saves++;},()=> 'r-1');
assert.equal(state.reactions.length,1);
assert.equal(state.reactions[0].sourceStory.storyId,'story-2');
assert.equal(result.pending(state,'2026-11-03',storyState).length,0,'完了後は案内を消す');
result.save(state,entry,'none','',()=>{saves++;},()=> 'r-2');
assert.equal(state.reactions.length,1,'後から回答なしに変えても二重登録しない');
result.save(state,entry,'entered','後から届いた回答',()=>{saves++;},()=> 'r-3');
result.save(state,entry,'not-posted','',()=>{saves++;},()=> 'r-4');
assert.equal(state.reactions.length,1);
assert.equal(post.actualAt,undefined,'Storyを投稿しなかった記録で投稿状態を変えない');
assert.throws(()=>result.save(state,entry,'entered','失敗',()=>{throw Error('save failed');},()=> 'r-5'));
assert.equal(state.reactions[0].story2ResultStatus,'not-posted','保存失敗時は戻す');
assert.equal(JSON.stringify({posts:state.posts,records:state.records}),original,'Story企画と7日後評価を変更しない');
assert.equal(JSON.parse(JSON.stringify(state)).reactions[0].story2ResultStatus,'not-posted','再読み込み後も保持');
post.stories=stories('会話');
assert.equal(result.pending(state,'2026-11-02',storyState).length,0,'質問なしの日には案内しない');
post.stories=stories('質問スタンプ');
assert.equal(result.entries(state,'2026-11-03',storyState).length,1,'質問も同じ経路で扱う');
const standalone={id:'standalone-2',date:'2026-11-02',slot:2,text:'選んでください',kind:'二択',options:['A','B'],skuIds:[]};
state.storyDays=[standalone];
assert.equal(result.pending(state,'2026-11-02',storyState).length,0,'独立Storyも翌日から');
assert.deepEqual(result.pending(state,'2026-11-03',storyState).map(entry=>entry.story.id),['standalone-2'],'独立Storyの予定日を使う');

const html=fs.readFileSync('./dist/index.html','utf8');
for(const [,script] of html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g))if(script.trim())new vm.Script(script);
assert.match(html,/v7-story2-result\.js\?story2=/);
assert.match(html,/\[data-nav="results"\]\{display:none!important\}/,'独立画面の入口を隠す');
assert.match(html,/dx\('#homeReactionListEntry'\)\?\.remove\(\)/);
assert.match(html,/querySelector\('\[data-share-open\]'\)\?\.remove\(\)/);
assert.match(html,/data-story2-pending/);
assert.match(html,/story2ResultButtons\(dx\('#dayDetail'\)\)/,'元Story2から結果を編集');
assert.match(html,/voice\.answers=\[\.\.\.new Set/,'次期10日プランへ結果を渡す');
const editorial=fs.readFileSync('./dist/chatgpt-editorial.js','utf8');
const feedbackSource=editorial.slice(editorial.indexOf('function feedbackContext('),editorial.indexOf('function reviewContext('));
const feedbackContext={nextPlanFeedbackContext:()=>({instruction:'提案のみ',comments:[],savedCustomerVoices:[{id:'r-1',date:'2026-11-01',kind:'アンケート',question:'どちら？',answers:['まとめた結果'],options:[],dm:[],skuIds:[],uses:[],story2ResultStatus:'entered'}]})};
