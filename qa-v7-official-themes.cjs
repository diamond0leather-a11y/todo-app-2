const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const crypto=require('node:crypto');
const root=__dirname;
const lines=fs.readFileSync(path.join(root,'v7-official-themes.txt'),'utf8').trimEnd().split(/\r?\n/);
assert.equal(lines.length,100);
assert.equal(crypto.createHash('sha256').update(lines.join('\n')).digest('hex'),'3587a823739e42fdce627da3c65ee766c099acf435515443f2cb0decde306d2a','User-confirmed 2026-10-30 titles differ');
const asset=fs.readFileSync(path.join(root,'dist','v7-official-themes.js'),'utf8');
const publicTitles=vm.runInNewContext(asset+';V7_OFFICIAL_THEME_TITLES');
const groups=vm.runInNewContext(asset+';V7_OFFICIAL_THEME_GROUPS');
assert.deepEqual(Array.from(publicTitles),lines);
assert.equal(groups.length,10);
const source=fs.readFileSync(path.join(root,'three-axis.js'),'utf8');
const match=source.match(/const V7_OFFICIAL_THEME_TITLES=(\[[^;]+\]);/);
assert(match);
assert.deepEqual(Array.from(vm.runInNewContext(match[1])),lines);
const html=fs.readFileSync(path.join(root,'dist','index.html'),'utf8');
assert(html.includes('<script src="./v7-official-themes.js"></script>'));
const legacy=fs.readFileSync(path.join(root,'official-themes.txt'),'utf8').trimEnd().split(/\r?\n/);
assert.equal(legacy.length,100);
assert.equal(legacy[20],'牛革の特徴');
assert.equal(legacy[65],'日本の革産業は今どうなっている？');
assert.equal(lines[20],'牛・馬・山羊・羊など、革による違い');
assert.equal(lines[65],'荷物が多い人・少ない人で選び方はどう違う？');
assert.equal(lines[98],'いただいた声、その後どうなった？');
const legacyIds=legacy.map((_,i)=>'official-'+String(i+1).padStart(2,'0'));
const v7Ids=lines.map((_,i)=>'v7-official-'+String(i+1).padStart(2,'0'));
assert.equal(new Set([...legacyIds,...v7Ids]).size,200);
assert(html.includes('const LEGACY_OFFICIAL_TOPICS=OFFICIAL_TOPICS'));
assert(html.includes('return V7_OFFICIAL_TOPICS.map(topic=>'));
assert(html.includes('officialTopicOptions(p.parentId)'));
assert(html.includes('officialThemes:V7_OFFICIAL_TOPICS,legacyOfficialThemes:LEGACY_OFFICIAL_TOPICS'));
console.log('v7 official themes identity and source QA: PASS');
